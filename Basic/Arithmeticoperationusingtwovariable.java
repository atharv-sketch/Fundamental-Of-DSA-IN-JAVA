package Basic.DirectResult.Mathematicaloperation.morebasics.operators.variablebasics;

public class Arithmeticoperationusingtwovariable {
    static void main(String[] args) {
        int x = 39;
        int y = 10;
        System.out.println(x + y);
        System.out.println(x - y);
        System.out.println(x * y);
        System.out.println(x / y);
    }
}
